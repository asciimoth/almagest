        mock.chmod(0o755)
        for name in ('git', 'just', 'goreleaser', 'gh', 'gpg', 'go', 'gcc',
                     'pkg-config', 'docker', 'node', 'npm', 'cargo', 'golangci-lint',
                     'markdownlint', 'ripsecrets', 'pwsh', 'shellcheck', 'actionlint',
                     'typos', 'jq', 'notify-send', 'ghrepo'):
            (self.root / 'tools' / name).symlink_to(mock)

package main

import (
	"bytes"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/asciimoth/almagest/certcat/internal/catalog"
)

type renderRefs struct {
	recordScopes  []int
	scopes        []catalog.Scope
	recordCutoffs []int
	cutoffs       []platformCutoff
}

type platformCutoff struct {
	SCTTimestampAfter string
	EnforcementStart  string
	FirstMajorVersion uint16
}

func main() {
	manualPath := flag.String("manual", "data/manual.json", "manual JSON path")
	machinePath := flag.String("machine", "data/machine.json", "machine JSON path")
	outPath := flag.String("out", "catalog_gen.go", "generated Go output path")
	packageName := flag.String("package", "certcat", "generated Go package name")
	flag.Parse()

	manual, err := catalog.LoadDocument(*manualPath)
	if err != nil {
		fatal(err)
	}
	machine, err := catalog.LoadDocument(*machinePath)
	if err != nil {
		fatal(err)
	}
	if err := catalog.MachineSourcesValid(*machine); err != nil {
		fatal(err)
	}
	records, err := catalog.MergeDocuments(manual, machine)
	if err != nil {
		fatal(err)
	}
	src, err := render(*packageName, records)
	if err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*outPath, src, 0o644); err != nil {
		fatal(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s with %d merged records\n", *outPath, len(records))
}

func render(packageName string, records []catalog.Record) ([]byte, error) {
	refs, err := collectRefs(records)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by certcat-generate; DO NOT EDIT.")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	if err := writeScopeTable(&b, refs.scopes); err != nil {
		return nil, err
	}
	writePlatformCutoffTable(&b, refs.cutoffs)
	fmt.Fprintln(&b, "var Records = []Record{")
	for n, rec := range records {
		if err := writeRecord(&b, rec, refs.recordScopes[n], refs.recordCutoffs[n]); err != nil {
			return nil, err
		}
	}
	fmt.Fprintln(&b, "}")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return formatted, nil
}

func collectRefs(records []catalog.Record) (renderRefs, error) {
	refs := renderRefs{
		recordScopes:  make([]int, len(records)),
		recordCutoffs: make([]int, len(records)),
	}
	for n := range refs.recordScopes {
		refs.recordScopes[n] = -1
		refs.recordCutoffs[n] = -1
	}
	scopeByKey := map[string]int{}
	cutoffByKey := map[string]int{}
	for n, rec := range records {
		if !scopeEmpty(rec.Scope) {
			key := scopeKey(rec.Scope)
			scopeIndex, ok := scopeByKey[key]
			if !ok {
				scopeIndex = len(refs.scopes)
				scopeByKey[key] = scopeIndex
				refs.scopes = append(refs.scopes, rec.Scope)
			}
			refs.recordScopes[n] = scopeIndex
		}
		cutoff, ok, err := platformCutoffFromConditions(rec.Conditions)
		if err != nil {
			return renderRefs{}, fmt.Errorf("%s: %w", rec.ID, err)
		}
		if ok {
			key := cutoffKey(cutoff)
			cutoffIndex, ok := cutoffByKey[key]
			if !ok {
				cutoffIndex = len(refs.cutoffs)
				cutoffByKey[key] = cutoffIndex
				refs.cutoffs = append(refs.cutoffs, cutoff)
			}
			refs.recordCutoffs[n] = cutoffIndex
		}
	}
	return refs, nil
}

func writeRecord(b *bytes.Buffer, rec catalog.Record, scopeIndex, cutoffIndex int) error {
	writeComment(b, rec)
	matchKind, fingerprint, err := recordMatch(rec)
	if err != nil {
		return err
	}
	kind, err := codeConst(rec.Kind, kindConsts, "kind")
	if err != nil {
		return fmt.Errorf("%s: %w", rec.ID, err)
	}
	action, err := codeConst(rec.Action, actionConsts, "action")
	if err != nil {
		return fmt.Errorf("%s: %w", rec.ID, err)
	}
	severity, err := codeConst(rec.Severity, severityConsts, "severity")
	if err != nil {
		return fmt.Errorf("%s: %w", rec.ID, err)
	}
	fmt.Fprintln(b, "\t{")
	if err := writeFingerprintField(b, fingerprint); err != nil {
		return fmt.Errorf("%s: %w", rec.ID, err)
	}
	writeConstField(b, "MatchKind", matchKind)
	writeConstField(b, "Kind", kind)
	if rec.HazardClass != "" {
		hazardClass, err := codeConst(rec.HazardClass, hazardClassConsts, "hazard_class")
		if err != nil {
			return fmt.Errorf("%s: %w", rec.ID, err)
		}
		writeConstField(b, "HazardClass", hazardClass)
	}
	writeConstField(b, "Action", action)
	writeConstField(b, "Severity", severity)
	if rec.Recommendation != "" {
		recommendation, err := codeConst(rec.Recommendation, recommendationConsts, "recommendation")
		if err != nil {
			return fmt.Errorf("%s: %w", rec.ID, err)
		}
		writeConstField(b, "Recommendation", recommendation)
	}
	if scopeIndex >= 0 {
		fmt.Fprintf(b, "\t\tScope: &recordScopes[%d],\n", scopeIndex)
	}
	if cutoffIndex >= 0 {
		fmt.Fprintf(b, "\t\tPlatformCutoff: &recordPlatformCutoffs[%d],\n", cutoffIndex)
	}
	fmt.Fprintln(b, "\t},")
	return nil
}

func writeComment(b *bytes.Buffer, rec catalog.Record) {
	switch {
	case rec.ID != "" && rec.Name != "":
		fmt.Fprintf(b, "\t// %s: %s\n", sanitizeComment(rec.ID), sanitizeComment(rec.Name))
	case rec.ID != "":
		fmt.Fprintf(b, "\t// %s\n", sanitizeComment(rec.ID))
	case rec.Name != "":
		fmt.Fprintf(b, "\t// %s\n", sanitizeComment(rec.Name))
	}
	if len(rec.Sources) > 0 {
		fmt.Fprintln(b, "\t// Sources:")
		for _, src := range rec.Sources {
			line := "- " + src.ID + ": " + src.URL
			if src.RetrievedAt != "" {
				line += " retrieved " + src.RetrievedAt
			}
			if src.Note != "" {
				line += " " + src.Note
			}
			fmt.Fprintf(b, "\t// %s\n", sanitizeComment(line))
		}
	}
}

func recordMatch(rec catalog.Record) (string, string, error) {
	switch {
	case rec.CertificateSHA256 != "":
		return "MatchKindCertificateSHA256", rec.CertificateSHA256, nil
	case rec.SPKISHA256 != "":
		return "MatchKindSPKISHA256", rec.SPKISHA256, nil
	default:
		return "", "", fmt.Errorf("%s: certificate_sha256 or spki_sha256 is required", rec.ID)
	}
}

func writeFingerprintField(b *bytes.Buffer, fingerprint string) error {
	decoded, err := hex.DecodeString(fingerprint)
	if err != nil {
		return fmt.Errorf("decode fingerprint: %w", err)
	}
	if len(decoded) != 32 {
		return fmt.Errorf("fingerprint must have 32 bytes")
	}
	fmt.Fprint(b, "\t\tFingerprint: Fingerprint{")
	for n, value := range decoded {
		if n > 0 {
			fmt.Fprint(b, ", ")
		}
		fmt.Fprintf(b, "0x%02X", value)
	}
	fmt.Fprintln(b, "},")
	return nil
}

func writeConstField(b *bytes.Buffer, name, value string) {
	fmt.Fprintf(b, "\t\t%s: %s,\n", name, value)
}

func writeStringField(b *bytes.Buffer, indent, name, value string) {
	if value == "" {
		return
	}
	fmt.Fprintf(b, "%s%s: %s,\n", indent, name, strconv.Quote(value))
}

func writeStringSliceField(b *bytes.Buffer, indent, name string, values []string) {
	if len(values) == 0 {
		return
	}
	fmt.Fprintf(b, "%s%s: []string{\n", indent, name)
	for _, value := range values {
		fmt.Fprintf(b, "%s\t%s,\n", indent, strconv.Quote(value))
	}
	fmt.Fprintf(b, "%s},\n", indent)
}

func writeScopeTable(b *bytes.Buffer, scopes []catalog.Scope) error {
	if len(scopes) == 0 {
		return nil
	}
	fmt.Fprintln(b, "var recordScopes = []Scope{")
	for _, scope := range scopes {
		fmt.Fprintln(b, "\t{")
		if scope.Basis != "" {
			basis, err := codeConst(scope.Basis, scopeBasisConsts, "scope.basis")
			if err != nil {
				return err
			}
			writeConstField(b, "Basis", basis)
		}
		writeStringSliceField(b, "\t\t", "PermittedDNSSubtrees", scope.PermittedDNSSubtrees)
		writeStringSliceField(b, "\t\t", "PermittedIPCIDRs", scope.PermittedIPCIDRs)
		if scope.RequiresExplicitAllowlist {
			fmt.Fprintln(b, "\t\tRequiresExplicitAllowlist: true,")
		}
		if scope.RejectIPTargets {
			fmt.Fprintln(b, "\t\tRejectIPTargets: true,")
		}
		fmt.Fprintln(b, "\t},")
	}
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
	return nil
}

func writePlatformCutoffTable(b *bytes.Buffer, cutoffs []platformCutoff) {
	if len(cutoffs) == 0 {
		return
	}
	fmt.Fprintln(b, "var recordPlatformCutoffs = []PlatformCutoff{")
	for _, cutoff := range cutoffs {
		fmt.Fprintln(b, "\t{")
		writeStringField(b, "\t\t", "SCTTimestampAfter", cutoff.SCTTimestampAfter)
		writeStringField(b, "\t\t", "EnforcementStart", cutoff.EnforcementStart)
		if cutoff.FirstMajorVersion != 0 {
			fmt.Fprintf(b, "\t\tFirstMajorVersion: %d,\n", cutoff.FirstMajorVersion)
		}
		fmt.Fprintln(b, "\t},")
	}
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
}

func sanitizeComment(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	return strings.TrimSpace(s)
}

func scopeEmpty(scope catalog.Scope) bool {
	return scope.Basis == "" &&
		len(scope.PermittedDNSSubtrees) == 0 &&
		len(scope.PermittedIPCIDRs) == 0 &&
		!scope.RequiresExplicitAllowlist &&
		!scope.RejectIPTargets
}

func scopeKey(scope catalog.Scope) string {
	parts := []string{
		scope.Basis,
		strings.Join(scope.PermittedDNSSubtrees, "\x00"),
		strings.Join(scope.PermittedIPCIDRs, "\x00"),
		strconv.FormatBool(scope.RequiresExplicitAllowlist),
		strconv.FormatBool(scope.RejectIPTargets),
	}
	return strings.Join(parts, "\x01")
}

func platformCutoffFromConditions(values map[string]string) (platformCutoff, bool, error) {
	if len(values) == 0 {
		return platformCutoff{}, false, nil
	}
	sctTimestampAfter := values["chrome_sct_timestamp_after"]
	enforcementStart := values["chrome_enforcement_started"]
	firstMajorVersion := values["chrome_first_major_version"]
	if len(values) != 3 || sctTimestampAfter == "" || enforcementStart == "" || firstMajorVersion == "" {
		return platformCutoff{}, false, fmt.Errorf("unsupported conditions")
	}
	version, err := strconv.ParseUint(firstMajorVersion, 10, 16)
	if err != nil {
		return platformCutoff{}, false, fmt.Errorf("parse chrome_first_major_version: %w", err)
	}
	return platformCutoff{
		SCTTimestampAfter: sctTimestampAfter,
		EnforcementStart:  enforcementStart,
		FirstMajorVersion: uint16(version),
	}, true, nil
}

func cutoffKey(cutoff platformCutoff) string {
	return strings.Join([]string{
		cutoff.SCTTimestampAfter,
		cutoff.EnforcementStart,
		strconv.FormatUint(uint64(cutoff.FirstMajorVersion), 10),
	}, "\x00")
}

func codeConst(value string, values map[string]string, field string) (string, error) {
	constName, ok := values[value]
	if !ok {
		return "", fmt.Errorf("unknown %s %q", field, value)
	}
	return constName, nil
}


#!/usr/bin/env python3
"""Generate stable WiX components for tracked locales and examples."""

import argparse
import hashlib
import subprocess
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "packaging" / "windows" / "payload.wxs"
NAMESPACES = {
    "locales": uuid.UUID("7297B181-3669-464C-A02A-FC83D6D9BA09"),
    "examples": uuid.UUID("D4E6AC07-C273-4BD7-B5CA-2A27D454D50C"),
}


def tracked_files(tree: str) -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", tree],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return [line for line in result.stdout.splitlines() if line]


def wix_id(prefix: str, path: str) -> str:
    digest = hashlib.sha256(path.encode()).hexdigest()[:24]
    return f"{prefix}_{digest}"


def component(tree: str, path: str) -> list[str]:
    relative = Path(path).relative_to(tree)
    subdirectory = str(relative.parent).replace("/", "\\")
    subdirectory_attribute = ""
    if subdirectory != ".":
        subdirectory_attribute = f' Subdirectory="{subdirectory}"'
    component_id = wix_id(tree.title(), path)
    file_id = wix_id("File", path)
    guid = str(uuid.uuid5(NAMESPACES[tree], path)).upper()
    source = "$(var.SourceDir)\\" + path.replace("/", "\\")
    return [
        f'    <Component Id="{component_id}" Directory="{tree.upper()}FOLDER"',
        f'               Guid="{guid}"{subdirectory_attribute}>',
        f'      <File Id="{file_id}" Source="{source}" KeyPath="yes" />',
        "    </Component>",
    ]


def render() -> str:
    lines = [
        "<!-- Generated by generate-payload-wxs.py. Do not edit. -->",
        '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">',
        '  <Fragment>',
    ]
    groups: dict[str, list[str]] = {}
    for tree in NAMESPACES:
        paths = tracked_files(tree)
        groups[tree] = [wix_id(tree.title(), path) for path in paths]
        for path in paths:
            lines.extend(component(tree, path))
    lines.extend(["  </Fragment>", ""])
    for tree, ids in groups.items():
        lines.extend([
            "  <Fragment>",
            f'    <ComponentGroup Id="{tree.title()}Components">',
        ])
        lines.extend(f'      <ComponentRef Id="{value}" />' for value in ids)
        lines.extend(["    </ComponentGroup>", "  </Fragment>", ""])
    lines.extend(["</Wix>", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            parser.error(f"{OUTPUT.relative_to(ROOT)} is not current")
        return 0
    OUTPUT.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

// Package daemonservices defines the local service contracts used to compose
// almagestd. These contracts describe in-process Go calls. They are not a wire
// protocol and do not define transport messages or remote resource handles.
package daemonservices

import (
	"crypto/sha256"
	"errors"
	"fmt"

	"github.com/asciimoth/almagest/bin/almagestd/command"
	"github.com/asciimoth/gonnect/sysnet"
)

// HostNetwork is the local host-network service contract. Direct mode keeps
// the full sysnet surface and returns backend networks and TUNs unchanged so
// native fast paths stay intact. This local contract is not an IPC schema.
type HostNetwork interface {
	sysnet.System
}

// ConfigSource supplies the two startup configuration documents.
type ConfigSource interface {
	ReadConfig() (config, protected []byte, err error)
	// ConfRO reports whether the regular configuration source is read-only.
	// The name is retained from the existing platform contract.
	ConfRO() bool
}

var (
	ErrConfigRevisionConflict = errors.New("config persistence revision conflict")
	ErrConfigOperationUnknown = errors.New("config persistence operation is unknown")
)

// ConfigDocument is the opaque regular config and its content revision.
type ConfigDocument struct {
	Data     []byte
	Revision string
}

// ConfigOperationResult is a retained result of one replace operation.
// Error is empty only when the replacement committed.
type ConfigOperationResult struct {
	OperationID string
	Revision    string
	Error       string
}

// Err converts an operation result to the error seen by the runtime.
func (r ConfigOperationResult) Err() error {
	if r.Error == "" {
		return nil
	}
	if r.Error == ErrConfigRevisionConflict.Error() {
		return ErrConfigRevisionConflict
	}
	return errors.New(r.Error)
}

// ConfigRevision returns the content revision used by config persistence.
func ConfigRevision(data []byte) string {
	return fmt.Sprintf("%x", sha256.Sum256(data))
}

// ConfigPersistence reads and replaces one regular-config target selected at
// startup. No method accepts a path or protected-config selector.
type ConfigPersistence interface {
	ReadCurrent() (ConfigDocument, error)
	Replace(expectedRevision, operationID string, config []byte) ConfigOperationResult
	GetResult(operationID string) (ConfigOperationResult, error)
}

// NodeCommandDispatcher dispatches requests made by command nodes. The local
// implementation must enforce the protected AllowNodes setting independently
// of node menus and workspace configuration. It intentionally has no method
// that accepts an executable or argv.
type NodeCommandDispatcher interface {
	SubmitNodeCommand(command.Request) bool
}

// BackendCallbackDispatcher dispatches commands generated by trusted backend
// lifecycle callbacks. It is separate from NodeCommandDispatcher so runtime
// nodes cannot acquire callback command authority.
type BackendCallbackDispatcher interface {
	SubmitBackendCallback(command.Request) bool
}

// Lifecycle owns one composed application and releases it exactly once.
type Lifecycle interface {
	Close() error
}

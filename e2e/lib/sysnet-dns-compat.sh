#!/usr/bin/env bash
set -euo pipefail

run_sysnet_dns_compat() {
	local flavor="$1"
	local query_name="almagest-$flavor.e2e.test"
	local answer="203.0.113.53"
	local upstream_log="$E2E_RUNTIME/upstream-dns.log"
	local dnsmasq_pid=""
	local resolved_pid=""
	local resolv_backup="$E2E_RUNTIME/resolv.conf.original"

	cp -a /etc/resolv.conf "$resolv_backup"

	cleanup_sysnet_dns_compat() {
		stop_daemon
		if [[ -n "$dnsmasq_pid" ]]; then
			kill "$dnsmasq_pid" 2>/dev/null || true
			wait "$dnsmasq_pid" 2>/dev/null || true
		fi
		if [[ -n "$resolved_pid" ]]; then
			kill "$resolved_pid" 2>/dev/null || true
			wait "$resolved_pid" 2>/dev/null || true
		fi
		if [[ -f "$resolv_backup" ]]; then
			cp -a "$resolv_backup" /etc/resolv.conf
		fi
	}
	trap cleanup_sysnet_dns_compat EXIT

	case "$flavor" in
	debian-resolvconf)
		resolvconf --version >"$E2E_RUNTIME/resolvconf-version.log" 2>&1 || true
		grep -F "Debian resolvconf" "$E2E_RUNTIME/resolvconf-version.log" >/dev/null \
			|| fail "resolvconf is not the Debian implementation"
		cat >/etc/resolv.conf <<'EOF'
# resolv.conf(5) file generated by resolvconf
# DO NOT EDIT THIS FILE BY HAND -- YOUR CHANGES WILL BE OVERWRITTEN
nameserver 127.0.0.54
EOF
		;;
	openresolv)
		resolvconf --version >"$E2E_RUNTIME/resolvconf-version.log" 2>&1 \
			|| fail "openresolv did not report its version"
		if grep -F "Debian resolvconf" "$E2E_RUNTIME/resolvconf-version.log" >/dev/null; then
			fail "resolvconf is the Debian implementation, not openresolv"
		fi
		cat >/etc/resolv.conf <<'EOF'
# resolv.conf(5) file generated by resolvconf
# DO NOT EDIT THIS FILE BY HAND -- YOUR CHANGES WILL BE OVERWRITTEN
nameserver 127.0.0.54
EOF
		;;
	systemd-resolved)
		mkdir -p /run/dbus /etc/systemd
		dbus-daemon --system --fork
		cat >/etc/systemd/resolved.conf <<'EOF'
[Resolve]
DNSStubListener=yes
FallbackDNS=
EOF
		/lib/systemd/systemd-resolved >"$E2E_RUNTIME/systemd-resolved.log" 2>&1 &
		resolved_pid="$!"
		retry "$ALMAGEST_E2E_TIMEOUT" "systemd-resolved D-Bus service" \
			busctl --system call org.freedesktop.resolve1 /org/freedesktop/resolve1 \
			org.freedesktop.DBus.Peer Ping >/dev/null \
			|| fail "systemd-resolved did not register on D-Bus"
		local upstream_octets="${E2E_DNS_UPSTREAM//./ }"
		local upstream_ifidx
		upstream_ifidx="$(cat /sys/class/net/eth0/ifindex)"
		# shellcheck disable=SC2086
		busctl --system call org.freedesktop.resolve1 /org/freedesktop/resolve1 \
			org.freedesktop.resolve1.Manager SetLinkDNS "ia(iay)" \
			"$upstream_ifidx" 1 2 4 $upstream_octets >/dev/null
		busctl --system call org.freedesktop.resolve1 /org/freedesktop/resolve1 \
			org.freedesktop.resolve1.Manager SetLinkDefaultRoute "ib" \
			"$upstream_ifidx" true >/dev/null
		busctl --system call org.freedesktop.resolve1 /org/freedesktop/resolve1 \
			org.freedesktop.resolve1.Manager SetLinkDomains "ia(sb)" \
			"$upstream_ifidx" 1 . true >/dev/null
		cat >/etc/resolv.conf <<'EOF'
# This is /run/systemd/resolve/stub-resolv.conf managed by systemd-resolved.
nameserver 127.0.0.53
EOF
		;;
	*)
		fail "unsupported sysnet DNS compatibility flavor: $flavor"
		;;
	esac

	cat >"$E2E_RUNTIME/dnsmasq.conf" <<EOF
port=53
listen-address=$E2E_DNS_UPSTREAM
bind-interfaces
no-resolv
no-hosts
log-queries
log-facility=$upstream_log
address=/$query_name/$answer
EOF
	dnsmasq --no-daemon --conf-file="$E2E_RUNTIME/dnsmasq.conf" \
		>/dev/null 2>"$E2E_RUNTIME/dnsmasq.stderr" &
	dnsmasq_pid="$!"
	# The retry helper invokes these functions by name.
	# shellcheck disable=SC2329
	upstream_answers() {
		dig +time=1 +tries=1 +short "@$E2E_DNS_UPSTREAM" "$query_name" A \
			| grep -Fx "$answer" >/dev/null
	}
	retry "$ALMAGEST_E2E_TIMEOUT" "DNS upstream $E2E_DNS_UPSTREAM" \
		upstream_answers \
		|| fail "DNS upstream did not return $answer"

	start_daemon
	trap cleanup_sysnet_dns_compat EXIT
	wait_graph_node "DefaultTun DNS Manager" || fail "DefaultTun node missing"
	wait_graph_node "DNS Manager Upstream" || fail "DnsClient node missing"
	default_tun="$(node_id_by_name "DefaultTun DNS Manager")"
	dns_client="$(node_id_by_name "DNS Manager Upstream")"
	wait_node_label "$default_tun" ready || fail "DefaultTun did not become ready"
	wait_node_label "$dns_client" "1 DNS server" || fail "DnsClient did not become ready"

	if [[ "$flavor" == "systemd-resolved" ]]; then
		# The sysnet allocator randomizes the DefaultTun interface suffix.
		# shellcheck disable=SC2329
		resolved_has_almagest_dns() {
			resolvectl dns | awk '
				/^Link [0-9]+ \(alm/ && NF >= 4 { found = 1 }
				END { exit !found }
			'
		}
		retry "$ALMAGEST_E2E_TIMEOUT" "resolved DNS on the Almagest TUN" \
			resolved_has_almagest_dns >/dev/null \
			|| fail "systemd-resolved has no DNS configuration for the Almagest TUN"
	else
		local record
		local installed_server
		record="$(
			resolvconf -l sysnet-linux 2>/dev/null \
				|| resolvconf -l 2>/dev/null
		)"
		installed_server="$(
			awk '
				/^# resolv.conf from sysnet-linux$/ { owned = 1; next }
				owned && /^nameserver / { print $2; exit }
			' <<<"$record"
		)"
		[[ -n "$installed_server" ]] \
			|| fail "$flavor did not install a resolvconf nameserver record"
		# Docker bind-mounts /etc/resolv.conf. Mirror the real provider record
		# into that file, as the upstream sysnet-linux Docker suite does.
		printf '# mirrored %s record for Docker\nnameserver %s\n' \
			"$flavor" "$installed_server" >/etc/resolv.conf
	fi

	# shellcheck disable=SC2329
	resolve_name() {
		getent ahostsv4 "$query_name" | awk 'NR == 1 { print $1 }'
	}
	# shellcheck disable=SC2329
	system_resolves() {
		[[ "$(resolve_name)" == "$answer" ]]
	}
	retry "$ALMAGEST_E2E_TIMEOUT" "system query through $flavor" \
		system_resolves \
		|| fail "system resolver did not return $answer through $flavor"
	retry "$ALMAGEST_E2E_TIMEOUT" "$flavor upstream query" \
		grep -F "$query_name" "$upstream_log" >/dev/null \
		|| fail "upstream DNS did not receive $query_name"

	log "case passed: $flavor"
	cleanup_sysnet_dns_compat
	trap - EXIT
}
